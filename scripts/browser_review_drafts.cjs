const assert=require('node:assert/strict');
const {spawn}=require('node:child_process');
const {chromium}=require('playwright');
(async()=>{
 const server=spawn('python3',['-m','http.server','8767','--bind','127.0.0.1','--directory','dist']);let browser;
 try{
  for(let i=0;i<30;i++){try{await fetch('http://127.0.0.1:8767');break;}catch{await new Promise(r=>setTimeout(r,100));}}
  browser=await chromium.launch({headless:true});const page=await browser.newPage({viewport:{width:390,height:844}});
  await page.addInitScript(()=>{window.spoken=[];window.SpeechSynthesisUtterance=class{constructor(text){this.text=text;}};
    Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async(text)=>{window.copied=text;}}});
    Object.defineProperty(navigator,'share',{configurable:true,value:undefined});
    Object.defineProperty(window,'speechSynthesis',{value:{paused:false,speak(u){window.spoken.push(u.text);},pause(){this.paused=true;},resume(){this.paused=false;},cancel(){window.stopped=true;}}});});
  await page.goto('http://127.0.0.1:8767/review-drafts.html');
  await page.locator('main a[href^="review-drafts/"]').first().click();
  assert((await page.textContent('main')).includes('UNAPPROVED'));
  await page.click('#listen');assert((await page.evaluate(()=>window.spoken.length))>0);
  await page.click('#pause');assert.equal(await page.evaluate(()=>speechSynthesis.paused),true);
  await page.click('#pause');assert.equal(await page.evaluate(()=>speechSynthesis.paused),false);
  await page.click('#stop');assert.equal(await page.textContent('#speech-status'),'Stopped.');
  await page.click('[data-action="copy-article"]');
  assert((await page.evaluate(()=>window.copied)).includes('UNAPPROVED'));
  assert((await page.evaluate(()=>window.copied)).includes('Sources'));
  await page.goto('http://127.0.0.1:8767/articles.html');
  if(process.env.ARTICLE_QA_SCREENSHOT)await page.screenshot({path:process.env.ARTICLE_QA_SCREENSHOT,fullPage:true});
  const manifest=await page.evaluate(async()=>await (await fetch('data/publications.json')).json());
  assert.equal(await page.locator('.article-card').count(),manifest.articles.length);
  await page.click('[data-action="copy-all-links"]');
  assert((await page.evaluate(()=>window.copied)).includes('reverse-transcriptase-rna-to-dna-1970'));
  await page.fill('#article-search','jackpot');
  assert.equal(await page.locator('.article-card:visible').count(),1);
  await page.fill('#article-search','');
  await page.selectOption('#article-kind','story');
  assert.equal(await page.locator('.article-card:visible').count(),manifest.articles.filter(x=>x.kind==='story').length);
  await page.selectOption('#article-kind','all');
  await page.locator('a[data-article-url][href="articles/biological-compilation-amplified-individual.html"]').click();
  await page.click('[data-action="copy-article"]');
  assert((await page.evaluate(()=>window.copied)).includes('A tape measure'));
  assert((await page.evaluate(()=>window.copied)).includes('FDA'));
  await page.click('[data-action="share"]');
  assert.equal(await page.evaluate(()=>window.copied),'https://davidwpace.github.io/open-biomedical-resource-center/articles/biological-compilation-amplified-individual.html');
  await page.goto('http://127.0.0.1:8767/stories/penicillin.html');
  await page.click('#listen');
  assert((await page.evaluate(()=>window.spoken.length))>0);
  await page.click('[data-action="copy-article"]');
  assert((await page.evaluate(()=>window.copied)).includes('The mold that changed medicine'));
  const bundle=await page.request.get('http://127.0.0.1:8767/exports/all-articles.md');
  assert.equal(bundle.status(),200);assert((await bundle.text()).includes('PUBLIC MANUSCRIPT DRAFT'));
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  console.log('PASS: mobile library, filters, article copy, all links, share fallback, draft/legacy speech, sources and exports');
 }finally{if(browser)await browser.close();server.kill();}
})().catch(e=>{console.error(e);process.exitCode=1});
